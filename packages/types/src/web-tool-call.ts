/**
 * Web tool call analytics (the `web_tool_calls` table).
 *
 * The proxy intercepts Claude Code's `web_search` helper requests and serves
 * them from configured third-party search providers. Such a request never
 * selects an account, so it writes no `requests` row — this table is the only
 * record of it. One row per intercepted tool call, whatever the outcome.
 */

import type { DriverInteger } from "./search-provider";

export type { DriverInteger };

/**
 * Outcome of one intercepted tool call:
 * - `ok` — served locally; `result_count` is set (0 is valid: no results).
 * - `error` — a provider was tried and failed, and nothing else served it.
 * - `fallthrough` — interception was attempted but no provider was eligible
 *   (or the chain gave up), so the request went upstream. A normal outcome,
 *   worth measuring: it marks calls still paid for at Anthropic.
 */
export type WebToolCallStatus = "ok" | "error" | "fallthrough";

export const WEB_TOOL_CALL_STATUSES: readonly WebToolCallStatus[] = [
	"ok",
	"error",
	"fallthrough",
];

/**
 * A driver-returned row (snake_case). Every integer column is typed
 * {@link DriverInteger}: PostgreSQL surfaces BIGINT as a string, SQLite as a
 * number — `toWebToolCall` coerces them.
 */
export interface WebToolCallRow {
	id: string;
	timestamp: DriverInteger;
	tool: string; // 'web_search' (future: 'web_fetch')
	provider_id: string | null;
	provider_kind: string | null; // 'tavily', ...
	account_id: string | null;
	project: string | null;
	query_text: string | null;
	query_chars: DriverInteger;
	result_count: DriverInteger | null;
	latency_ms: DriverInteger;
	status: string;
	error_code: string | null;
	estimated_cost_usd: number | string | null;
}

/** Domain model — all integers coerced to numbers. */
export interface WebToolCall {
	id: string;
	timestamp: number;
	tool: string;
	providerId: string | null;
	providerKind: string | null;
	accountId: string | null;
	project: string | null;
	queryText: string | null;
	queryChars: number;
	resultCount: number | null;
	latencyMs: number;
	status: WebToolCallStatus;
	errorCode: string | null;
	/** Placeholder — always null today (cost modelling deprioritised). */
	estimatedCostUsd: number | null;
}

/**
 * Everything a caller may supply. `id` and `timestamp` are generated by the
 * repository. `providerId`/`providerKind` are absent on `fallthrough`;
 * `resultCount` is absent unless `status` is `ok`.
 */
export interface WebToolCallInput {
	tool: string;
	providerId?: string | null;
	providerKind?: string | null;
	accountId?: string | null;
	project?: string | null;
	queryText?: string | null;
	queryChars: number;
	resultCount?: number | null;
	latencyMs: number;
	status: WebToolCallStatus;
	errorCode?: string | null;
}

/**
 * Fully-resolved write payload. Same fields as {@link WebToolCallInput} except
 * the identity, which the repository fills in.
 */
export type WebToolCallWriteInput = WebToolCallInput;

/** One `(provider_kind, status)` bucket produced by the summary query. */
export interface WebToolCallSummary {
	providerKind: string | null;
	status: WebToolCallStatus;
	callCount: number;
	totalLatencyMs: number;
	avgLatencyMs: number;
	totalResults: number;
}

/** Coerce a driver integer (number on SQLite, string on PG BIGINT). */
function toInt(value: DriverInteger, fallback = 0): number {
	const parsed = typeof value === "number" ? value : Number(value);
	return Number.isFinite(parsed) ? parsed : fallback;
}

function toNullableInt(value: DriverInteger | null): number | null {
	if (value === null || value === undefined) return null;
	const parsed = typeof value === "number" ? value : Number(value);
	return Number.isFinite(parsed) ? parsed : null;
}

/** NUMERIC/float columns may arrive as strings; NaN falls back to 0. */
function toFloat(value: number | string | null, fallback = 0): number {
	if (value === null || value === undefined) return fallback;
	const parsed = typeof value === "number" ? value : Number(value);
	return Number.isFinite(parsed) ? parsed : fallback;
}

/** Nullable float: null in, null out (estimated_cost_usd stays NULL today). */
function toNullableFloat(value: number | string | null): number | null {
	if (value === null || value === undefined) return null;
	const parsed = typeof value === "number" ? value : Number(value);
	return Number.isFinite(parsed) ? parsed : null;
}

/** Row → domain model (Row -> Domain, like `toSearchProvider`). */
export function toWebToolCall(row: WebToolCallRow): WebToolCall {
	return {
		id: row.id,
		timestamp: toInt(row.timestamp),
		tool: row.tool,
		providerId: row.provider_id ?? null,
		providerKind: row.provider_kind ?? null,
		accountId: row.account_id ?? null,
		project: row.project ?? null,
		queryText: row.query_text ?? null,
		queryChars: toInt(row.query_chars),
		resultCount: toNullableInt(row.result_count),
		latencyMs: toInt(row.latency_ms),
		status: row.status as WebToolCallStatus,
		errorCode: row.error_code ?? null,
		estimatedCostUsd: toNullableFloat(row.estimated_cost_usd),
	};
}

/** Raw summary row as the driver returns it (snake_case / PG string ints). */
export interface WebToolCallSummaryRow {
	provider_kind: string | null;
	status: string;
	call_count: DriverInteger;
	total_latency_ms: DriverInteger | null;
	avg_latency_ms: number | string | null;
	total_results: DriverInteger | null;
}

/** Summary row → domain model. */
export function toWebToolCallSummary(
	row: WebToolCallSummaryRow,
): WebToolCallSummary {
	return {
		providerKind: row.provider_kind ?? null,
		status: row.status as WebToolCallStatus,
		callCount: toInt(row.call_count),
		totalLatencyMs: toInt(row.total_latency_ms ?? 0),
		avgLatencyMs: toFloat(row.avg_latency_ms),
		totalResults: toInt(row.total_results ?? 0),
	};
}
